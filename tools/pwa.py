#!/usr/bin/env python3
"""Make an app work offline and installable on the phone (owner, 2026-10-30): writes manifest.webmanifest, icon.svg and sw.js
into apps/<slug>/ and links them from its index.html. The service worker keeps the app, assets/design.css, assets/quran.js
and data/quran.json on the device (cache-first) and the Google fonts after their first load. Safe to re-run: the cache name
carries a hash of the cached files, so every change reaches the phones on their next visit.
Usage: python3 tools/pwa.py apps/<slug> [apps/<slug> ...]      (or --all for every app in apps.json)"""
import os, re, sys, json, hashlib
R = os.path.dirname(os.path.dirname(os.path.abspath(__file__))) + '/'
SHARED = ['assets/design.css', 'assets/quran.js', 'data/quran.json']

SW = '''/* generated by tools/pwa.py — do not edit by hand, re-run the tool */
const CACHE = '%(cache)s';
const FILES = %(files)s;
self.addEventListener('install', e => e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES)).then(() => self.skipWaiting())));
self.addEventListener('activate', e => e.waitUntil(caches.keys().then(ks => Promise.all(
  ks.filter(k => k.startsWith('%(slug)s-') && k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim())));
self.addEventListener('fetch', e => {
  const u = new URL(e.request.url);
  if (e.request.method !== 'GET') return;
  if (u.hostname.endsWith('fonts.googleapis.com') || u.hostname.endsWith('fonts.gstatic.com')) {
    e.respondWith(caches.open(CACHE + '-fonts').then(c => c.match(e.request).then(hit => {
      const net = fetch(e.request).then(r => { if (r.ok || r.type === 'opaque') c.put(e.request, r.clone()); return r; }).catch(() => hit);
      return hit || net;
    })));
    return;
  }
  if (u.origin !== location.origin) return;
  e.respondWith(caches.match(e.request, {ignoreSearch: true}).then(hit => hit || fetch(e.request)));
});
'''

ICON = '''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512"><rect width="512" height="512" rx="112" fill="#0F6B4F"/>
<path d="M256 120c-46 30-92 36-136 30v190c44 6 90 0 136-30 46 30 92 36 136 30V150c-44 6-90 0-136-30z" fill="none" stroke="#F6EBCF" stroke-width="22" stroke-linejoin="round"/>
<path d="M256 120v220" stroke="#F6EBCF" stroke-width="22"/><circle cx="256" cy="400" r="18" fill="#E0BD62"/></svg>
'''

REGISTER = ('<script>if (\'serviceWorker\' in navigator) addEventListener(\'load\', function () '
            '{ navigator.serviceWorker.register(\'sw.js\'); });</script>')


def registry():
    p = R + 'apps.json'
    return json.load(open(p, encoding='utf8')) if os.path.exists(p) else {'apps': []}


def add(app_dir):
    d = os.path.join(R, app_dir.strip('/')) + '/'
    slug = os.path.basename(d.rstrip('/'))
    page = d + 'index.html'
    if not os.path.exists(page): sys.exit('no index.html in ' + d)
    meta = next((a for a in registry()['apps'] if a['slug'] == slug), {})
    html = open(page, encoding='utf8').read()
    title = meta.get('title') or re.search(r'<title>(.*?)</title>', html, re.S).group(1).strip()

    json.dump({'name': title, 'short_name': meta.get('short') or title[:12], 'description': meta.get('desc', ''),
               'lang': 'ar', 'dir': 'rtl', 'start_url': './', 'scope': './', 'display': 'standalone',
               'background_color': '#F6F3EC', 'theme_color': '#0F6B4F',
               'icons': [{'src': 'icon.svg', 'sizes': 'any', 'type': 'image/svg+xml', 'purpose': 'any maskable'}]},
              open(d + 'manifest.webmanifest', 'w', encoding='utf8'), ensure_ascii=False, indent=1)
    open(d + 'icon.svg', 'w', encoding='utf8').write(ICON)

    head = ''
    if 'rel="manifest"' not in html: head += '<link rel="manifest" href="manifest.webmanifest">\n'
    if 'rel="icon"' not in html: head += '<link rel="icon" href="icon.svg" type="image/svg+xml">\n'
    if 'apple-touch-icon' not in html: head += '<link rel="apple-touch-icon" href="icon.svg">\n'
    if head: html = html.replace('</head>', head + '</head>', 1)
    if "serviceWorker.register('sw.js')" not in html: html = html.replace('</body>', REGISTER + '\n</body>', 1)
    open(page, 'w', encoding='utf8').write(html)

    # the app's own files plus the shared ones, as URLs relative to the app folder
    own = sorted(os.path.relpath(os.path.join(a, f), d) for a, _, fs in os.walk(d) for f in fs if f != 'sw.js')
    files = ['./'] + [f for f in own if f != 'index.html'] + ['../../' + s for s in SHARED]
    h = hashlib.sha1()
    for f in own: h.update(open(d + f, 'rb').read())
    for s in SHARED: h.update(open(R + s, 'rb').read())
    open(d + 'sw.js', 'w', encoding='utf8').write(SW % {'cache': '%s-%s' % (slug, h.hexdigest()[:10]), 'slug': slug,
                                                       'files': json.dumps(files, ensure_ascii=False)})
    print('pwa ok:', app_dir, '(%d files cached)' % len(files))


if __name__ == '__main__':
    args = sys.argv[1:]
    if args == ['--all']: args = ['apps/' + a['slug'] for a in registry()['apps']]
    if not args: sys.exit(__doc__)
    for a in args: add(a)
