#!/usr/bin/env python3
"""Start a new Quran app from the shared template (owner, 2026-10-30): copies templates/app/ to apps/<slug>/, registers it in
apps.json, rebuilds the home page index.html from apps.json, and makes it work offline (tools/pwa.py).
Usage: python3 tools/new_app.py <slug> "<العنوان>" "<وصف في سطر>" [--short "<اسم قصير>"] [--tags "حفظ,تلاوة"]
       python3 tools/new_app.py --index        (only rebuild index.html from apps.json, e.g. after editing a title)
slug: lowercase English letters, digits and dashes (it becomes the link: /quran/apps/<slug>/)."""
import os, re, sys, json, shutil, datetime, html as H
R = os.path.dirname(os.path.dirname(os.path.abspath(__file__))) + '/'
sys.path.insert(0, R + 'tools'); sys.dont_write_bytecode = True
import pwa

STATUS = {'draft': 'قيد البناء', 'ready': 'جاهز'}


def load():
    p = R + 'apps.json'
    return json.load(open(p, encoding='utf8')) if os.path.exists(p) else {'apps': []}


def save(reg):
    json.dump(reg, open(R + 'apps.json', 'w', encoding='utf8'), ensure_ascii=False, indent=2)
    open(R + 'apps.json', 'a', encoding='utf8').write('\n')


def build_index(reg):
    cards = ''.join(
        '<a class="card" href="apps/%s/"><h2>%s</h2><p class="muted">%s</p><div class="row">%s</div></a>' % (
            H.escape(a['slug']), H.escape(a['title']), H.escape(a.get('desc', '')),
            ''.join('<span class="chip%s">%s</span>' % (' gold' if t == STATUS.get(a.get('status')) else '', H.escape(t))
                    for t in [STATUS.get(a.get('status'), a.get('status', ''))] + a.get('tags', []) if t))
        for a in reg['apps']) or '<p class="muted">لا توجد تطبيقات بعد. أنشئ أول تطبيق بـ <code>tools/new_app.py</code>.</p>'
    page = INDEX.replace('{{cards}}', cards).replace('{{count}}', str(len(reg['apps'])))
    open(R + 'index.html', 'w', encoding='utf8').write(page)


INDEX = '''<!doctype html>
<html lang="ar" dir="rtl">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">
<meta name="description" content="تطبيقات قرآنية تعليمية من منصة أفق">
<meta name="theme-color" content="#0F6B4F">
<title>تطبيقات القرآن</title>
<link rel="stylesheet" href="assets/design.css">
</head>
<body>
<!-- generated by tools/new_app.py from apps.json — edit apps.json and run: python3 tools/new_app.py --index -->
<header class="app-bar">
  <h1>📖 تطبيقات القرآن</h1>
  <button class="btn icon-btn" id="theme" type="button" aria-label="الوضع الفاتح أو الداكن">🌓</button>
</header>
<main class="page">
  <p class="muted">{{count}} تطبيق · كل الآيات من نص المصحف الموثّق في هذا المستودع.</p>
  <div class="grid">{{cards}}</div>
</main>
<script src="assets/quran.js"></script>
<script>Quran.Theme.init(document.getElementById('theme'));</script>
</body>
</html>
'''


def main():
    a = sys.argv[1:]
    reg = load()
    if a == ['--index']:
        build_index(reg); print('index.html rebuilt:', len(reg['apps']), 'apps'); return
    opts = {}
    for k in ('--short', '--tags'):
        if k in a:
            i = a.index(k); opts[k] = a[i + 1]; del a[i:i + 2]
    if len(a) != 3: sys.exit(__doc__)
    slug, title, desc = a
    if not re.fullmatch(r'[a-z0-9]+(-[a-z0-9]+)*', slug): sys.exit('slug must look like: tajweed-quiz')
    d = R + 'apps/' + slug + '/'
    if os.path.exists(d) or any(x['slug'] == slug for x in reg['apps']): sys.exit('apps/%s already exists' % slug)
    shutil.copytree(R + 'templates/app', d)
    p = d + 'index.html'
    t = open(p, encoding='utf8').read()
    for k, v in (('{{TITLE}}', H.escape(title)), ('{{DESC}}', H.escape(desc)), ('{{SLUG}}', slug)): t = t.replace(k, v)
    open(p, 'w', encoding='utf8').write(t)
    entry = {'slug': slug, 'title': title, 'desc': desc, 'status': 'draft',
             'tags': [x.strip() for x in opts.get('--tags', '').split(',') if x.strip()],
             'created': datetime.date.today().isoformat()}
    if '--short' in opts: entry['short'] = opts['--short']
    reg['apps'].append(entry)
    save(reg)
    build_index(reg)
    pwa.add('apps/' + slug)
    print('new app:', 'apps/%s/' % slug, '— now build it, then: node tools/app_check.mjs %s && python3 tools/quran_check.py' % slug)


if __name__ == '__main__': main()
